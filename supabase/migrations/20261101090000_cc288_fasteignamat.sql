-- cc288 — FASTEIGNAMAT HMS Á /markadur: mat eftir árgerð, flokkun atvinnuhúsnæðis og röðun gatna/svæða.
--
-- ÁKVARÐANIR 31.10 (bindandi, SKIL_CC288 § Smíði):
--   · Aðaltala = fasteignamat HMS 2026 (gildandi), merkt árgerð. 2027 = sér tölfræði (breyting) úr HMS-safni 3.–5.6.2026.
--   · Engin persónuverndarhlið (fasteignamat er opinbert per fastanúmer). Lágmark eingöngu tölfræðilegt: n ≥ 5 (regla 13).
--   · Íbúðir: miðgildi kr/m² á íbúðum 60–150 m² (aðal) + miðgildi mats á eign. Atvinnuhúsnæði: kr/m² PER FLOKK, aldrei „alls“.
--   · „annad_atvinnu“ og óflokkað er talið (v_fasteignamat_keyrsla.talning) en ALDREI raðað (CHECK á hopur).
--   · Sveitarfélagsheiti eru btrim-uð hér (properties.sveitarfelag ber hala af bilum: 124 gildi / 62 svfn). Aðrir fletir ósnertir.
-- GRUNNREGLA 8: ekkert hér les eða vísar í predictions, comps eða þrep. Kassinn er birtingarlag úr opinberu mati.
-- cc284d: nýir hlutir fá EKKERT sjálfkrafa — anon/authenticated fá SELECT á sýnirnar tvær hér að neðan, ekkert annað.
-- Gögn: migration býr aðeins til skema + flokkun. Hleðsla og röðun: scripts/cc288_fasteignamat.py (ekki í næturkeðju).
-- Eining: þús. kr (sama og properties/kaupskrá) nema midg_kr_m2 sem er í KRÓNUM á m².

CREATE TABLE semantic.fasteignamat_argerd (
  fastnum      bigint   NOT NULL,
  argerd       smallint NOT NULL CHECK (argerd BETWEEN 2020 AND 2040),
  mat_thkr     numeric  NOT NULL CHECK (mat_thkr > 0),
  lhlmat_thkr  numeric,
  heimild      text     NOT NULL CHECK (heimild IN ('properties.fasteignamat_hms', 'hms_safn.fasteignamat_naesta_ar', 'hms_safn.fasteignamat')),
  sott         date     NOT NULL,
  PRIMARY KEY (fastnum, argerd)
);
COMMENT ON TABLE semantic.fasteignamat_argerd IS
  'cc288: fasteignamat HMS per fastanúmer og árgerð (langt snið; ný árgerð = ný röð, aldrei uppfærsla á staðnum — cc82-reglan). ÞÚS. KR. 2026 úr properties.fasteignamat_hms; 2027 úr HMS-safni (fasteignamat_naesta_ar, sótt 3.–5.6.2026).';

CREATE TABLE semantic.atvinnu_flokkun (
  tegund         text PRIMARY KEY CHECK (tegund = btrim(regexp_replace(tegund, '\s+', ' ', 'g'))),
  yfirflokkur    text NOT NULL CHECK (yfirflokkur IN ('atvinnu', 'utan')),
  flokkur        text NOT NULL CHECK (flokkur IN ('verslun','skrifstofa','idnadur_lager','gisting','annad_atvinnu','sumarhus','lod_land','bilskur_geymsla','stofnun_opinber','veitur_innvidir','landbunadur','ibudarurraedi')),
  radast         boolean GENERATED ALWAYS AS (flokkur IN ('verslun', 'skrifstofa', 'idnadur_lager', 'gisting')) STORED,
  regla_version  text NOT NULL DEFAULT 'cc288-v1',
  CHECK ((yfirflokkur = 'atvinnu') = (flokkur IN ('verslun', 'skrifstofa', 'idnadur_lager', 'gisting', 'annad_atvinnu')))
);
COMMENT ON TABLE semantic.atvinnu_flokkun IS
  'cc288: tegund_raw (HMS notkun_texti, bil normuð) → flokkur. Tegund sem er EKKI í töflunni er óflokkuð og fer aldrei í röðun. Heimild: D:/_audit/cc288_fasteignamat/scripts/flokkun.py, TAXONOMY.md §4.';

CREATE TABLE semantic.fasteignamat_keyrslur (
  keyrsla_id       bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  regla_version    text        NOT NULL,
  argerd           smallint    NOT NULL,
  argerd_breyting  smallint,
  sott_argerd      date        NOT NULL,
  sott_breyting    date,
  reiknad_at       timestamptz NOT NULL DEFAULT now(),
  lagmark_n        int         NOT NULL CHECK (lagmark_n = 5),
  staerdarbil_ibud numrange    NOT NULL,
  talning          jsonb       NOT NULL,
  n_rodun          int         NOT NULL,
  md5_rodun        text        NOT NULL,
  virk             boolean     NOT NULL DEFAULT false,
  athugasemd       text
);
CREATE UNIQUE INDEX fasteignamat_keyrslur_ein_virk ON semantic.fasteignamat_keyrslur (virk) WHERE virk;

CREATE TABLE semantic.fasteignamat_rodun (
  keyrsla_id          bigint   NOT NULL REFERENCES semantic.fasteignamat_keyrslur (keyrsla_id) ON DELETE CASCADE,
  argerd              smallint NOT NULL,
  hopur               text     NOT NULL CHECK (hopur IN ('ibud', 'verslun', 'skrifstofa', 'idnadur_lager', 'gisting')),
  tegund              text     NOT NULL CHECK (tegund IN ('allt', 'fjolbyli', 'serbyli')),
  stig                text     NOT NULL CHECK (stig IN ('gata', 'matsvaedi', 'postnr', 'svf', 'land')),
  lykill              text     NOT NULL,
  heiti               text     NOT NULL CHECK (heiti = btrim(heiti)),
  gata                text,
  postnr              int,
  matsvaedi_numer     int,
  svfn                int,
  svf                 text CHECK (svf = btrim(svf)),
  n                   int      NOT NULL CHECK (n >= 1),
  n_kr_m2             int      NOT NULL CHECK (n_kr_m2 BETWEEN 0 AND n),
  midg_kr_m2          numeric,
  midg_mat_eign_thkr  numeric,
  heildarmat_thkr     numeric,
  midg_flm            numeric,
  n_breyting          int      NOT NULL CHECK (n_breyting BETWEEN 0 AND n),
  breyting_pct        numeric,
  PRIMARY KEY (keyrsla_id, hopur, tegund, stig, lykill),
  CHECK (hopur = 'ibud' OR tegund = 'allt'),
  -- regla 13 í gögnunum sjálfum: miðgildi og breyting eru NULL undir lágmarki (5)
  CHECK (midg_kr_m2 IS NULL OR n_kr_m2 >= 5),
  CHECK (midg_mat_eign_thkr IS NULL OR n >= 5),
  CHECK (breyting_pct IS NULL OR n_breyting >= 5),
  CHECK ((stig = 'gata') = (gata IS NOT NULL))
);
COMMENT ON TABLE semantic.fasteignamat_rodun IS
  'cc288: röðunargrunnur kassans „Fasteignamat HMS <árgerð>“ á /markadur. Ein röð per (keyrsla, hópur, tegund, stig, lykill), hver með n. Lesist um semantic.v_fasteignamat_rodun.';

ALTER TABLE semantic.fasteignamat_argerd   ENABLE ROW LEVEL SECURITY;
ALTER TABLE semantic.atvinnu_flokkun       ENABLE ROW LEVEL SECURITY;
ALTER TABLE semantic.fasteignamat_keyrslur ENABLE ROW LEVEL SECURITY;
ALTER TABLE semantic.fasteignamat_rodun    ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON semantic.fasteignamat_argerd, semantic.atvinnu_flokkun, semantic.fasteignamat_keyrslur, semantic.fasteignamat_rodun
  FROM PUBLIC, anon, authenticated;

-- Lesflöturinn: aðeins virka keyrslan og aðeins raðir með n ≥ 5.
CREATE VIEW semantic.v_fasteignamat_rodun AS
SELECT r.argerd, k.argerd_breyting, r.hopur, r.tegund, r.stig, r.lykill, r.heiti, r.gata, r.postnr, r.matsvaedi_numer, r.svfn, r.svf,
       r.n, r.n_kr_m2,
       CASE WHEN r.n_kr_m2 >= 5 THEN r.midg_kr_m2 END          AS midg_kr_m2,
       CASE WHEN r.n >= 5 THEN r.midg_mat_eign_thkr END         AS midg_mat_eign_thkr,
       r.heildarmat_thkr, r.midg_flm,
       r.n_breyting,
       CASE WHEN r.n_breyting >= 5 THEN r.breyting_pct END      AS breyting_pct,
       k.regla_version, k.sott_argerd, k.sott_breyting, k.reiknad_at
  FROM semantic.fasteignamat_rodun r
  JOIN semantic.fasteignamat_keyrslur k ON k.keyrsla_id = r.keyrsla_id AND k.virk
 WHERE r.n >= 5;

CREATE VIEW semantic.v_fasteignamat_keyrsla AS
SELECT argerd, argerd_breyting, sott_argerd, sott_breyting, reiknad_at, regla_version, lagmark_n,
       lower(staerdarbil_ibud) AS ibud_m2_fra, upper(staerdarbil_ibud) AS ibud_m2_til, talning
  FROM semantic.fasteignamat_keyrslur WHERE virk;

REVOKE ALL ON semantic.v_fasteignamat_rodun, semantic.v_fasteignamat_keyrsla FROM PUBLIC, anon, authenticated;
GRANT SELECT ON semantic.v_fasteignamat_rodun, semantic.v_fasteignamat_keyrsla TO anon, authenticated;

