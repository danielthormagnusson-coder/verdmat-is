-- Hlið: dreifing lykla nákvæmlega eins og mælt; thunnt_svaedi = þrepareglan (engin prior, < 3 comps, < 8 á svæði).
DO $$ DECLARE n_staerd_othekkt int; n_landbunadur_sumarhus int; n_utihus int; n_staerd_utan int; n_gogn_vantar int; n_thunnt_svaedi int; n_brot int; BEGIN
  SELECT count(*) INTO n_staerd_othekkt FROM public.valuation_tiers WHERE t5_astaeda = 'staerd_othekkt';
  SELECT count(*) INTO n_landbunadur_sumarhus FROM public.valuation_tiers WHERE t5_astaeda = 'landbunadur_sumarhus';
  SELECT count(*) INTO n_utihus FROM public.valuation_tiers WHERE t5_astaeda = 'utihus';
  SELECT count(*) INTO n_staerd_utan FROM public.valuation_tiers WHERE t5_astaeda = 'staerd_utan';
  SELECT count(*) INTO n_gogn_vantar FROM public.valuation_tiers WHERE t5_astaeda = 'gogn_vantar';
  SELECT count(*) INTO n_thunnt_svaedi FROM public.valuation_tiers WHERE t5_astaeda = 'thunnt_svaedi';
  SELECT count(*) INTO n_brot FROM public.valuation_tiers
   WHERE t5_astaeda IN ('thunnt_svaedi','gogn_vantar') AND (has_prior_tier OR n_comps >= 3 OR n_svaedi >= 8);
  IF NOT (n_staerd_othekkt = 159 AND n_landbunadur_sumarhus = 36 AND n_utihus = 1368 AND n_staerd_utan = 266 AND n_gogn_vantar = 0 AND n_thunnt_svaedi = 2535 AND n_brot = 0) THEN
