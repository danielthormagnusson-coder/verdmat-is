-- Hlið á stöðu: listinn = 1829 raðir, allar T5 í lifandi töflu; T5 alls 4.364 (ef þrepin hafa breyst: HALT, nýr listi/mæling).
DO $$ DECLARE n_l int; n_t5 int; n_utan int; BEGIN
  SELECT count(*) INTO n_l FROM cc375_listi;
  SELECT count(*) INTO n_t5 FROM public.valuation_tiers WHERE tier = 'T5';
  SELECT count(*) INTO n_utan FROM cc375_listi l LEFT JOIN public.valuation_tiers v USING (fastnum)
   WHERE v.tier IS DISTINCT FROM 'T5';
  IF n_l <> 1829 OR n_t5 <> 4364 OR n_utan <> 0 THEN
    RAISE EXCEPTION 'HALT: listi %, T5 %, listi utan T5 % (vænt 1829 / 4364 / 0)', n_l, n_t5, n_utan;
  END IF;
END $$;

